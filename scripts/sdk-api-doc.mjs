#!/usr/bin/env node
// Writes (default) or checks (--check) the generated API list in docs/sdk.md from the REAL runtime exports of
// @seam/sdk and @seam/sdk/browser (built dist). Type-only exports are not runtime values and are not listed.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import * as prettier from "prettier";

const root = fileURLToPath(new URL("..", import.meta.url));
const doc = `${root}docs/sdk.md`;
const START = "<!-- api:start (generated by scripts/sdk-api-doc.mjs, do not edit) -->";
const END = "<!-- api:end -->";

export async function renderApi() {
  const node = await import(`${root}packages/sdk/dist/index.js`);
  const browser = await import(`${root}packages/sdk/dist/browser.js`);
  const row = (m, k) => `| \`${k}\` | ${typeof m[k]} |`;
  const table = (m) =>
    [
      "| export | kind |",
      "| --- | --- |",
      ...Object.keys(m)
        .sort()
        .map((k) => row(m, k)),
    ].join("\n");
  return [
    START,
    "",
    `### \`@seam/sdk\` (${Object.keys(node).length} runtime exports)`,
    "",
    table(node),
    "",
    `### \`@seam/sdk/browser\` (${Object.keys(browser).length} runtime exports, each \`===\` the same export of \`@seam/sdk\`)`,
    "",
    table(browser),
    "",
    END,
  ].join("\n");
}

const text = readFileSync(doc, "utf8");
const a = text.indexOf(START),
  b = text.indexOf(END);
if (a < 0 || b < 0) throw new Error("docs/sdk.md is missing the api markers");
// Format the same way `prettier --write docs/sdk.md` would, so the check is stable under formatting.
const rendered = text.slice(0, a) + (await renderApi()) + text.slice(b + END.length);
const formatted = await prettier.format(rendered, {
  ...(await prettier.resolveConfig(doc)),
  filepath: doc,
});
const want = formatted.slice(formatted.indexOf(START), formatted.indexOf(END) + END.length);
const have = text.slice(a, b + END.length);
if (process.argv.includes("--check")) {
  if (have !== want) {
    console.error(
      "docs/sdk.md API reference differs from the real exports. Run: node scripts/sdk-api-doc.mjs",
    );
    process.exit(1);
  }
  console.log("docs/sdk.md API reference matches the real exports");
} else {
  writeFileSync(doc, formatted);
  console.log("docs/sdk.md API reference written");
}
