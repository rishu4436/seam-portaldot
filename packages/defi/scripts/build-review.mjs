import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { keccak256, stringToHex } from "viem";
const built = JSON.parse(readFileSync(resolve("packages/defi/artifacts/contracts.json"), "utf8"));
const names = [
  "SeamTestToken",
  "SeamReferencePool",
  "SeamReferenceVault",
  "SeamGuardRouter",
  "SeamTestMarket",
];
const contracts = Object.fromEntries(
  names.map((name) => [
    name,
    {
      runtime: built.contracts[name].runtime,
      immutableReferences: built.contracts[name].immutableReferences,
    },
  ]),
);
const review = {
  compiler: built.compiler,
  openZeppelin: built.openZeppelin,
  sourceSha256: built.sourceSha256,
  evmVersion: built.settings.evmVersion,
  optimizerRuns: built.settings.optimizer.runs,
  viaIR: built.settings.viaIR,
  classification: "engineering-reviewed-test-market; not independently audited",
  factoryCreationCode: built.contracts.SeamTestMarket.bytecode,
  contracts,
};
const reviewId = keccak256(stringToHex(JSON.stringify(review)));
const output = `// Generated by npm run defi:review. Do not edit bytecode or immutable ranges by hand.\n// Engineering review record: docs/defi-v3-engineering-review.md. This is not an independent audit.\nexport const V3_PROGRAM = ${JSON.stringify({ reviewId, ...review }, null, 2)} as const;\n`;
writeFileSync(resolve("packages/defi/src/reviewed-v3.ts"), output);
console.log(
  JSON.stringify({
    reviewId,
    compiler: review.compiler,
    sourceSha256: review.sourceSha256,
    contracts: names,
  }),
);
